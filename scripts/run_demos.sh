#!/usr/bin/env bash
# Runs the seven final demos against samples/navgps-c and writes transcripts to docs/demos/ + docs/DEMOS.md.
# Usage: scripts/run_demos.sh [--direct]   (default: the local AI model phrases the answers)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
MODE="${1:---llm}"
S="$ROOT/bin/verity"; P="$ROOT/samples/navgps-c"; OUT="$ROOT/docs/demos"; mkdir -p "$OUT"
"$S" index "$P" > "$OUT/0-index.txt" 2>&1
qs=("Explain how GPS data travels through this application."
    "What does ProcessGpsData() do?"
    "What is the purpose of currentHeading?"
    "What happens when GPS sends heading 270?"
    "What happens if GPS becomes unavailable?"
    "What could be affected if I change CalculateHeading()?")
i=1
for q in "${qs[@]}"; do
  echo "[demo $i] $q"
  "$S" ask "$P" "$q" --details $MODE > "$OUT/$i.txt" 2>&1
  i=$((i+1))
done
echo "[demo 7] open the evidence: nav/navigation.c:59"
"$S" source "$P" nav/navigation.c:59 > "$OUT/7-source.txt" 2>&1
{
  echo "# Verity — final demos (generated by scripts/run_demos.sh $MODE on $(date '+%Y-%m-%d %H:%M'))"
  echo
  echo "Project: \`samples/navgps-c\`. Every transcript below is the unedited output of \`bin/verity ask … --details\`."
  echo
  echo "## Indexing"; echo '```'; cat "$OUT/0-index.txt"; echo '```'
  i=1
  for q in "${qs[@]}"; do
    echo; echo "## Demo $i — $q"; echo '```'; cat "$OUT/$i.txt"; echo '```'; i=$((i+1))
  done
  echo; echo "## Demo 7 — click the evidence, see the source (CLI: \`verity source <project> nav/navigation.c:59\`; desktop: click any Evidence row)"
  echo '```'; cat "$OUT/7-source.txt"; echo '```'
} > "$ROOT/docs/DEMOS.md"
echo "wrote docs/DEMOS.md"
